/** The width of a byte past ASCII, in millionths of an em. */
const OTHER_BYTE = 277832;

/** The widths for a font family, by its name as a layout source writes it. */
function widthsOf(family: string, bold: boolean, italic: boolean): number[] {
  const f = family.toLowerCase();
  if (f === 'helvetica' || f === 'arial') return bold ? HELVETICA_BOLD : HELVETICA;
  if (/^courier( new)?$/.test(f)) return COURIER;
  if (bold) return italic ? TIMES_BOLD_ITALIC : TIMES_BOLD;
  return italic ? TIMES_ITALIC : TIMES;
}

/** How many bytes a character takes in UTF-8. */
const utf8Bytes = (code: number) => (code < 0x80 ? 1 : code < 0x800 ? 2 : code < 0x10000 ? 3 : 4);

/** The width of `text` in points, at `size` points, in `family`, bold or italic, as Graphviz estimates it. */
export function textWidth(text: string, size: number, family = 'Times-Roman', bold = false, italic = false): number {
  const widths = widthsOf(family, bold, italic);
  let units = 0;
  for (const ch of text) {
    const code = ch.codePointAt(0) as number;
    units += code >= 32 && code < 127 ? (widths[code - 32] as number) : code < 32 ? 0 : utf8Bytes(code) * OTHER_BYTE;
  }
  return (units / 1e6) * size;
}
